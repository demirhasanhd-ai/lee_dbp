export function programTyycGroups(level, rows = []) {
  const tyycLevel = level === "Doktora" ? 8 : 7;
  return rows.length
    ? [{ id: "program-document", title: `TYYÇ ${tyycLevel}. Düzey Yeterlilikleri`, items: rows.map(({ code, title }) => ({ code, title })) }]
    : tyycGroups[tyycLevel];
}

// Validate raw input before normalization: a missing selection must never become 0 (Yok).
export function programTyycValidationMessage(profile, savedRows = []) {
  const outcomeCount = Array.isArray(profile.outcomes) ? profile.outcomes.length : 0;
  if (!outcomeCount) return "PÇ–TYYÇ İlişki Matrisi için en az bir program çıktısı tanımlayın.";
  const rows = Array.isArray(profile.tyycRows) ? profile.tyycRows : [];
  const expected = programTyycGroups(profile.level, savedRows).flatMap((group) => group.items);
  const issues = [];
  for (const item of [...expected, ...rows.filter((row) => row && !expected.some(({ code }) => code === row.code))]) {
    const matches = rows.filter((row) => row?.code === item.code);
    if (matches.length > 1) {
      issues.push(`${item.code}: Aynı TYYÇ satırı birden fazla kez gönderilmiş.`);
      continue;
    }
    const values = Array.isArray(matches[0]?.values) ? matches[0].values : [];
    const missing = [], invalid = [];
    for (let index = 0; index < outcomeCount; index++) {
      const value = values[index];
      if (value === null || value === undefined || value === "") missing.push(`PÇ${index + 1}`);
      else if (!Number.isInteger(value) || value < 0 || value > 3) invalid.push(`PÇ${index + 1}`);
    }
    if (missing.length) issues.push(`${item.code}: ${missing.join(", ")} için ilişki düzeyi seçilmemiş.`);
    if (invalid.length) issues.push(`${item.code}: ${invalid.join(", ")} için 0–3 arasında bir ilişki düzeyi seçin.`);
    if (values.length > outcomeCount) issues.push(`${item.code}: ${outcomeCount} program çıktısına karşılık ${values.length} değer var; fazla sütunları kaldırın.`);
  }
  return issues.length ? `PÇ–TYYÇ İlişki Matrisi eksik veya geçersiz; kayıt yapılmadı.\n${issues.join("\n")}` : "";
}

